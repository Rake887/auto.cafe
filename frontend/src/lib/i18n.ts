export type MessageKey = keyof typeof DICT;

export function t(lang: Lang, key: MessageKey): string {
  return DICT[key][lang] ?? DICT[key][DEFAULT_LANG];
}

export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && (LANGS as readonly string[]).includes(value);
}

/** Запомнить выбор языка на год — следующий стол откроется сразу на нём. */
export function rememberLang(lang: Lang): void {
  document.cookie = `${LANG_COOKIE}=${lang}; path=/; max-age=${60 * 60 * 24 * 365}`;
}

/** Ссылка с сохранением выбранного языка. */
export function withLang(path: string, lang: Lang): string {
  return lang === DEFAULT_LANG ? path : `${path}${path.includes("?") ? "&" : "?"}lang=${lang}`;
}
